type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("ka");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Language | null;
    if (saved === "ka" || saved === "en" || saved === "ru") setLanguageState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
    window.dispatchEvent(new CustomEvent("cheaper-language-changed", { detail: language }));
  }, [language]);

  const setLanguage = (l: Language) => {
    // write localStorage synchronously so formatGel/currencyLabel pick up
    // the new currency on the same render as the language change.
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, l);
      window.dispatchEvent(new CustomEvent("cheaper-language-changed", { detail: l }));
    }
    setLanguageState(l);
  };

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key: string) => labels[language][key] ?? labels.ka[key] ?? key,
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage, t } = useI18n();
  const options: { value: Language; label: string }[] = [
    { value: "ka", label: "ქარ" },
    { value: "en", label: "EN" },
    { value: "ru", label: "РУ" },
  ];

  return (
    <div
      role="group"
      aria-label={t("language")}
      className="inline-flex items-center rounded-full border border-border bg-card p-0.5 shadow-soft gap-0.5"
    >
      {options.map((option) => {
        const active = language === option.value;
        return (
          <button
            key={option.value}
            type="button"
            onClick={() => setLanguage(option.value)}
            aria-pressed={active}
            aria-label={option.label}
            title={option.label}
            className={`inline-flex items-center justify-center rounded-full font-bold leading-none transition-colors ${
              compact
                ? "min-w-[36px] h-8 px-2.5 text-[11px]"
                : "min-w-[44px] h-9 px-3 text-xs"
            } ${
              active
                ? "bg-primary text-primary-foreground shadow-sm"
                : "text-foreground hover:bg-muted"
            }`}
          >
            {option.label}
          </button>
        );
      })}
    </div>
  );
}
